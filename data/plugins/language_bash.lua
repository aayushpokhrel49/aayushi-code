-- mod-version:4
local syntax = require "core.syntax"

syntax.add {
  name = "Bash",
  files = { "%.sh$", "%.bash$" },
  headers = "^#!.*[ /]bash",
  comment = "#",
  patterns = {
    { pattern = "#[^\n]*",                    type = "comment"  },
    { pattern = "%$[%({][%w_]:?[%+%-=]?%b{}", type = "keyword2" },
    { pattern = "%$%(%s*[%w_]+%s*%)",         type = "keyword2" },
    { pattern = "%$[%a_][%w_]*",              type = "keyword2" },
    { pattern = { '"', '"', '\\' },           type = "string"   },
    { pattern = { "'", "'" },                 type = "string"   },
    { pattern = { '`', '`', '\\' },           type = "string"   },
    { pattern = "-?%d+[%d%.]*",               type = "number"   },
    { pattern = "%f[^%w_=]=",                 type = "operator" },
    { pattern = "[%+%-=/%*%^%%<>!~|&]",       type = "operator" },
    { pattern = "%f[[%.%w_/]-]%[%w_/%.%-+]", type = "function"  },
    { pattern = "%-%-[%w_-]+",                type = "keyword2" },
    { pattern = "%-%a",                       type = "keyword2" },
    { pattern = "[%a_][%w_]*",                type = "symbol"   },
  },
  symbols = {
    ["if"]         = "keyword",
    ["then"]       = "keyword",
    ["else"]       = "keyword",
    ["elif"]       = "keyword",
    ["fi"]         = "keyword",
    ["for"]        = "keyword",
    ["while"]      = "keyword",
    ["until"]      = "keyword",
    ["do"]         = "keyword",
    ["done"]       = "keyword",
    ["case"]       = "keyword",
    ["esac"]       = "keyword",
    ["function"]   = "keyword",
    ["in"]         = "keyword",
    ["select"]     = "keyword",
    ["time"]       = "keyword",
    ["local"]      = "keyword",
    ["readonly"]   = "keyword",
    ["export"]     = "keyword",
    ["return"]     = "keyword",
    ["exit"]       = "keyword",
    ["break"]      = "keyword",
    ["continue"]   = "keyword",
    ["cd"]         = "function",
    ["echo"]       = "function",
    ["printf"]     = "function",
    ["test"]       = "function",
    ["source"]     = "function",
    ["true"]       = "literal",
    ["false"]      = "literal",
  },
}